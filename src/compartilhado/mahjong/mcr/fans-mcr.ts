export const fanMcrPorId = (id: number) => FANS_MCR.find((fan) => fan.id === id)

/** Busca por nome em português, 汉字, inglês, yaku do Riichi ou número, sem acentos e sem caixa. */
export function buscarFansMcr(fans: readonly FanMcr[], termo: string): FanMcr[] {
  const normalizar = (texto: string) =>
    texto
      .normalize('NFD')
      .replace(/\p{Diacritic}/gu, '')
      .toLowerCase()
      .trim()
  const busca = normalizar(termo)
  if (!busca) return [...fans]
  return fans.filter(
    (fan) =>
      String(fan.id) === busca ||
      [fan.pt, fan.hanzi, fan.en, fan.yakuRiichi ?? ''].some((campo) =>
        normalizar(campo).includes(busca),
      ),
  )
}
